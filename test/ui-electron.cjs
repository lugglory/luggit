const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');

app.disableHardwareAcceleration();
const deadline = setTimeout(() => { console.error('Plugin UI timed out'); app.exit(1); }, 25000);
app.whenReady().then(async () => {
  console.log('Plugin UI: Electron ready');
  const win = new BrowserWindow({ width: 380, height: 840, show: false, webPreferences: { nodeIntegration: true, contextIsolation: false, backgroundThrottling: false } });
  win.webContents.on('console-message', (_event, ...args) => console.log('Renderer:', ...args));
  const capture = async filename => {
    await win.webContents.executeJavaScript('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    fs.writeFileSync(filename, (await win.webContents.capturePage()).toPNG());
  };
  try {
    await win.loadFile(path.join(__dirname, 'ui-fixture.html'));
    console.log('Plugin UI: fixture loaded');
    const result = await win.webContents.executeJavaScript('runTest()', true);
    assert.deepEqual(result.commands, ['open-panel', 'refresh']);
    assert.equal(result.quitRegistered, false);
    assert.equal(result.opened, 1);
    assert.equal(result.legacyIgnored, true);
    assert.equal(result.noCommitInput, true); assert.equal(result.noToolbar, true);
    assert.equal(result.overflow, false); assert.equal(result.iconOnly, true);
    assert.deepEqual(result.sectionStates, [true, true, true]);
    assert.deepEqual(result.titles, ['스테이지됨 (2)', '변경됨 (3)', '최근 변경한 파일']);
    assert.deepEqual(result.controls, ['내용 보존하며 충돌 해결', '내용 보존하며 충돌 해결']);
    await capture(path.join(os.tmpdir(), 'luggit-git-panel.png'));
    const panel = await win.webContents.executeJavaScript('runPanelOpenTest()', true);
    assert.deepEqual(panel, { afterOverlap: { created: 1, panels: 1 }, created: 0, types: ['markdown', 'luggit-changes'], keptFirst: true });
    win.setSize(960, 760);
    const conflict = await win.webContents.executeJavaScript('runConflictTest()', true);
    assert.deepEqual(conflict.labels, ['취소', '원본만 백업', '적용하고 해결로 표시']);
    assert.equal(conflict.focus, '취소'); assert.equal(conflict.cancelled, true);
    assert.equal(conflict.text, '공통 내용\n내 메모\n상대 메모\n');
    assert.equal(conflict.backupOnly, true);
    assert.deepEqual(conflict.calls, [{ name: '충돌한 메모.md', apply: true }, { name: '충돌한 메모.md', apply: false }]);
    await capture(path.join(os.tmpdir(), 'luggit-conflict.png'));
    await win.webContents.executeJavaScript('lastModal.close(); void 0');
    console.log('Panel and conflict UI passed: review-only controls, old sync settings ignored, preview, cancel, apply and backup.');
    const recent = await win.webContents.executeJavaScript('runRecentDiffTest()', true);
    assert.deepEqual(recent.queries, ['회의/제품 아이디어.md', '기록/삭제된 메모.md', '회의/제품 아이디어.md', '회의/제품 아이디어.md'], 'Recent diffs are requested only on demand');
    assert.deepEqual(recent.opened, Array(3).fill('회의/제품 아이디어.md'), 'Existing files open with a click anywhere in the window, or Enter or Space on the title');
    assert.equal(recent.results[0].openedBeforeClick, 0, 'Clicking a recent file opens its diff first; copy buttons and the end of a selection do not open the file');
    assert.equal(recent.results[0].hasOpen, false, 'The whole window opens the file, so there is no separate open button');
    assert.equal(recent.results[0].summaryButtons, 0, 'There is no open button above the diff either');
    assert.equal(recent.results[0].shortcutIgnored, true, 'Ctrl+Enter on the title and a click that ends a selection do not open or close the modal');
    assert.deepEqual(recent.copied, ['회의/제품 아이디어.md', '이전 1행 → 현재 1행\n-이전 아이디어\n+바뀐 아이디어',
      '기록/삭제된 메모.md', '이전 1행 → 삭제\n-삭제된 기록'], 'Copy buttons work for existing and deleted files without changing the system clipboard in the fixture');
    assert.equal(recent.results[0].hasTitleAction, true, 'An existing file title row opens its editor');
    assert.equal(recent.results[0].fullTitleRow, true, 'The blank right edge of the title row is also clickable');
    assert.equal(recent.results[1].hasOpen, false, 'Deleted files do not offer an unusable open action');
    assert.equal(recent.results[1].hasTitleAction, false, 'Deleted file titles remain plain text');
    assert.equal(recent.results[1].title, '기록/삭제된 메모.md');
    assert.equal(recent.results[1].label, '최근 변경 커밋 · 1234567');
    assert.equal(recent.results[1].removed, 1);
    assert.equal(recent.results[1].text.includes('/dev/null'), false);
    console.log('Recent-file UI passed: last-commit diff on click, deleted-file content, conditional open action.');
    win.setSize(960, 640);
    const diff = await win.webContents.executeJavaScript('runDiffTest()', true);
    assert.equal(diff.rows, 5);
    assert.deepEqual(diff.headings, ['이전', '현재', '', '변경 내용']);
    assert.equal(diff.text.includes('/dev/null'), false);
    assert.equal(diff.text.includes('diff --git'), false);
    assert.equal(diff.userSelect, 'text', 'Diff text overrides non-selectable host UI');
    win.webContents.debugger.attach('1.3');
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mousePressed', ...diff.start, button: 'left', buttons: 1, clickCount: 1 });
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseMoved', ...diff.end, button: 'left', buttons: 1 });
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseReleased', ...diff.end, button: 'left', buttons: 0, clickCount: 1 });
    assert.equal(await win.webContents.executeJavaScript('getSelection().toString()'), diff.expectedSelection, 'Mouse drag selects diff content');
    await win.webContents.executeJavaScript('document.execCommand("copy")', true);
    assert.deepEqual(await win.webContents.executeJavaScript('diffCopyEvents'), [diff.expectedSelection], 'Native copy receives the selected diff text');
    win.webContents.debugger.detach();
    const diffScreenshot = path.join(os.tmpdir(), 'luggit-diff.png');
    await capture(diffScreenshot);
    await win.webContents.executeJavaScript('lastModal.close(); void 0');
    console.log('Diff UI passed: readable new-file content, line numbers, no raw metadata. Screenshot: ' + diffScreenshot);
    await new Promise(resolve => { win.once('closed', resolve); win.close(); });
    console.log('Exit UI passed: uncommitted changes never block closing the window.');
    clearTimeout(deadline); app.exit(0);
  } catch (error) { console.error(error); clearTimeout(deadline); if (!win.isDestroyed()) win.destroy(); app.exit(1); }
});

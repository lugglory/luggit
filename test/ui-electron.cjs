const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');

app.disableHardwareAcceleration();
const deadline = setTimeout(() => { console.error('Plugin UI timed out'); app.exit(1); }, 25000);
app.whenReady().then(async () => {
  console.log('Plugin UI: Electron ready');
  const win = new BrowserWindow({ width: 380, height: 840, show: false, webPreferences: { nodeIntegration: true, contextIsolation: false, backgroundThrottling: false } });
  win.webContents.on('console-message', (_event, ...args) => console.log('Renderer:', ...args));
  const capture = async filename => {
    await win.webContents.executeJavaScript('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    fs.writeFileSync(filename, (await win.webContents.capturePage()).toPNG());
  };
  try {
    await win.loadFile(path.join(__dirname, 'ui-fixture.html'));
    console.log('Plugin UI: fixture loaded');
    const result = await win.webContents.executeJavaScript('runTest()', true);
    assert.equal(result.iconOnly, true, 'Every action button has icons and no visible text');
    assert.equal(result.combinedIcons, 1, 'Combined action uses one integrated commit/push icon');
    assert.deepEqual(result.calls, ['commit:테스트 커밋', 'push'], 'Click runs commit then push');
    assert.equal(result.overflow, false, 'Panel fits narrow sidebar');
    assert.equal(result.pending, true, 'Pending work is highlighted');
    assert.equal(result.toolbarAtTop, true, 'Commit controls sit above the message');
    assert.equal(result.noInlineStatus, true, 'Branch and status are absent from the panel');
    const sizing = result.messageSizing;
    assert.ok(sizing.initialHeight < 36, 'Commit message starts at one line');
    assert.ok(sizing.multilineHeight > sizing.initialHeight + 30, 'Newlines expand the message');
    assert.ok(sizing.wrappedHeight > sizing.multilineHeight, 'Wrapped text expands the message');
    assert.ok(sizing.narrowHeight > sizing.wideHeight, 'Sidebar width changes reflow the message');
    assert.equal(sizing.clearedHeight, sizing.initialHeight, 'Deleting text shrinks to one line');
    assert.equal(sizing.afterCommit, sizing.initialHeight, 'Successful commit resets the input height');
    assert.deepEqual(result.sectionActions, [['모두 스테이지 해제'], ['모두 버리기', '모두 스테이지']], 'Section actions remain available alongside the top toolbar');
    assert.deepEqual(result.topActions, ['커밋 후 Push', '커밋', '모두 스테이지', '모두 스테이지 해제', 'Push · 대기 커밋 2개', 'Pull · 원격 변경 가져오기']);
    assert.equal(result.toolbarNamedWithoutTooltip, true, 'Toolbar retains its accessible name without a Git 작업 tooltip');
    assert.equal(result.refreshClicks, 1, 'Pull button calls the remote refresh action');
    assert.equal(result.topActions.includes('모두 버리기'), false, 'Discard is absent from the top toolbar');
    assert.deepEqual(result.notices, ['커밋 후 Push 중…', '커밋 후 Push 완료'], 'Progress and result use notifications');
    win.webContents.debugger.attach('1.3');
    await win.webContents.debugger.sendCommand('DOM.enable');
    await win.webContents.debugger.sendCommand('CSS.enable');
    const { root } = await win.webContents.debugger.sendCommand('DOM.getDocument');
    const hover = async selector => {
      const { nodeId } = await win.webContents.debugger.sendCommand('DOM.querySelector', { nodeId: root.nodeId, selector });
      await win.webContents.debugger.sendCommand('CSS.forcePseudoState', { nodeId, forcedPseudoClasses: ['hover'] });
    };
    const styles = () => win.webContents.executeJavaScript(`(() => {
      const css = selector => getComputedStyle(document.querySelector(selector));
      const button = css('[aria-label="커밋 후 Push"]'), row = css('.luggit-file'), link = css('.luggit-path'), item = css('.luggit-file button');
      return { background: button.backgroundColor, color: button.color, border: button.borderTopWidth, shadow: button.boxShadow, row: row.backgroundColor, linkColor: link.color, underline: link.textDecorationLine, itemBackground: item.backgroundColor, itemBorder: item.borderTopWidth, itemShadow: item.boxShadow,
        sectionBackground: css('.luggit-section-header').backgroundColor, toggleBackground: css('.luggit-section-toggle').backgroundColor };
    })()`);
    const normal = await styles();
    assert.equal(normal.itemBackground, 'rgba(0, 0, 0, 0)');
    assert.equal(normal.itemBorder, '0px');
    assert.equal(normal.itemShadow, 'none');
    assert.equal(normal.background, 'rgba(0, 0, 0, 0)', 'Pending state keeps the button background transparent');
    assert.equal(normal.border, '0px');
    assert.equal(normal.shadow, 'none');
    assert.equal(normal.color, 'rgb(182, 164, 255)', 'Only the pending icon uses the accent color');
    await hover('[aria-label="커밋 후 Push"]');
    await hover('.luggit-file'); await hover('.luggit-path');
    await hover('.luggit-section-header');
    const hovered = await styles();
    assert.notEqual(hovered.background, normal.background, 'Buttons gain a background only on hover');
    assert.equal(hovered.color, normal.color, 'Pending icon retains its color on hover');
    assert.notEqual(hovered.row, normal.row, 'Git rows highlight on hover');
    assert.equal(hovered.linkColor, normal.linkColor, 'Filename color stays unchanged');
    assert.equal(hovered.underline, 'none', 'Filename does not gain an underline');
    assert.notEqual(hovered.sectionBackground, normal.sectionBackground, 'Hover highlights the entire section header');
    assert.equal(hovered.toggleBackground, 'rgba(0, 0, 0, 0)', 'The title button does not paint a separate partial highlight');
    const statusColors = await win.webContents.executeJavaScript(`(() => {
      const host = document.querySelector('.luggit'), probe = host.createDiv();
      const statuses = ['M', 'A', 'D', 'R', 'C', 'U', 'T', '?'];
      statuses.forEach(status => probe.createSpan({ text: status, cls: 'luggit-code', attr: { 'data-status': status } }));
      const colors = () => [...probe.children].map(el => getComputedStyle(el).color);
      const before = colors(); host.style.setProperty('--text-accent', '#000000'); host.style.setProperty('--text-normal', '#111111');
      const after = colors(); host.style.removeProperty('--text-accent'); host.style.removeProperty('--text-normal'); probe.remove();
      return { before, after, rendered: [...host.querySelectorAll('.luggit-code')].every(el => el.dataset.status === el.textContent) };
    })()`);
    assert.deepEqual(statusColors.before, statusColors.after, 'Status colors do not inherit theme colors');
    assert.equal(new Set(statusColors.before).size, 8, 'Each status has a distinct color');
    assert.equal(statusColors.rendered, true);
    const screenshot = path.join(os.tmpdir(), 'luggit-git-panel.png');
    await capture(screenshot);
    console.log('Plugin UI passed: icon-only controls, combined action, narrow layout. Screenshot: ' + screenshot);
    win.webContents.debugger.detach();
    const sections = await win.webContents.executeJavaScript('runSectionTest()', true);
    assert.equal(sections.states.length, 3);
    for (const state of sections.states) assert.deepEqual(state, { collapsed: true, stayedCollapsed: true, reopened: true, controlsList: true });
    for (const rect of sections.rects) {
      assert.equal(rect.width, 28); assert.equal(rect.rowWidth, 24);
      assert.ok(Math.abs(rect.centerOffset) < 1, 'Section action icons keep their alignment with file actions');
    }
    assert.equal(sections.expandedHitArea, true, 'The gap beside the file action is clickable in the section header');
    assert.deepEqual(sections.actions, ['스테이지']);
    assert.equal(sections.actionDidNotCollapse, true, 'Section actions do not toggle the section');
    assert.equal(sections.titleLeftAligned, true, 'Title alignment overrides centered host buttons');
    assert.equal(sections.headerCoversActions, true, 'Section highlight extends across the widened action buttons');
    assert.equal(sections.childIndent, 16, 'Child rows use a shallow indentation');
    const states = await win.webContents.executeJavaScript('runButtonStateTest()', true);
    assert.deepEqual(states.clean, { commitPush: 'enabled', commit: 'disabled', stage: 'disabled', unstage: 'disabled', push: 'enabled', pull: 'enabled' }, 'Nothing to do: certain no-ops are disabled; Push and Pull stay available');
    assert.deepEqual(states.waiting, { commitPush: 'enabled+highlight', commit: 'disabled', stage: 'disabled', unstage: 'disabled', push: 'enabled+highlight', pull: 'enabled' }, 'Waiting commits highlight Push and commit and push, which falls through to a plain push');
    assert.deepEqual(states.changed, { commitPush: 'enabled+highlight', commit: 'enabled+highlight', stage: 'enabled', unstage: 'disabled', push: 'enabled', pull: 'enabled' }, 'Changes highlight the commit actions; staging is a plain choice');
    assert.deepEqual(states.staged, { commitPush: 'enabled+highlight', commit: 'enabled+highlight', stage: 'disabled', unstage: 'enabled', push: 'enabled', pull: 'enabled' });
    const focus = await win.webContents.executeJavaScript('runPanelFocusTest()', true);
    assert.deepEqual(focus, { afterEntry: 0, afterInternal: 0, afterFileChanges: 1, pulls: 0, gap: '0px' }, 'Pointer and focus movement never refresh; file change requests coalesce into one local refresh; toolbar gaps are removed');
    const panelOpen = await win.webContents.executeJavaScript('runPanelOpenTest()', true);
    assert.deepEqual(panelOpen, { afterOverlap: { created: 1, panels: 1 }, created: 0, types: ['markdown', 'luggit-changes'], keptFirst: true },
      'Overlapping opens create one panel; a saved panel is reused before its view loads, and duplicates are removed');
    const recent = await win.webContents.executeJavaScript('runRecentDiffTest()', true);
    assert.deepEqual(recent.queries, ['회의/제품 아이디어.md', '기록/삭제된 메모.md', '회의/제품 아이디어.md', '회의/제품 아이디어.md'], 'Recent diffs are requested only on demand');
    assert.deepEqual(recent.opened, Array(3).fill('회의/제품 아이디어.md'), 'Existing files open with a click anywhere in the window, or Enter or Space on the title');
    assert.equal(recent.results[0].openedBeforeClick, 0, 'Clicking a recent file opens its diff first; copy buttons and the end of a selection do not open the file');
    assert.equal(recent.results[0].hasOpen, false, 'The whole window opens the file, so there is no separate open button');
    assert.equal(recent.results[0].summaryButtons, 0, 'There is no open button above the diff either');
    assert.equal(recent.results[0].shortcutIgnored, true, 'Ctrl+Enter on the title and a click that ends a selection do not open or close the modal');
    assert.deepEqual(recent.copied, ['회의/제품 아이디어.md', '이전 1행 → 현재 1행\n-이전 아이디어\n+바뀐 아이디어',
      '기록/삭제된 메모.md', '이전 1행 → 삭제\n-삭제된 기록'], 'Copy buttons work for existing and deleted files without changing the system clipboard in the fixture');
    assert.equal(recent.results[0].hasTitleAction, true, 'An existing file title row opens its editor');
    assert.equal(recent.results[0].fullTitleRow, true, 'The blank right edge of the title row is also clickable');
    assert.equal(recent.results[1].hasOpen, false, 'Deleted files do not offer an unusable open action');
    assert.equal(recent.results[1].hasTitleAction, false, 'Deleted file titles remain plain text');
    assert.equal(recent.results[1].title, '기록/삭제된 메모.md');
    assert.equal(recent.results[1].label, '최근 변경 커밋 · 1234567');
    assert.equal(recent.results[1].removed, 1);
    assert.equal(recent.results[1].text.includes('/dev/null'), false);
    console.log('Recent-file UI passed: last-commit diff on click, deleted-file content, conditional open action.');
    win.setSize(960, 640);
    const confirmation = await win.webContents.executeJavaScript('runConfirmationTest()', true);
    assert.deepEqual(confirmation.labels, ['취소', '변경 버리기']);
    assert.equal(confirmation.alignment, true);
    assert.equal(confirmation.focused, '변경 버리기');
    assert.deepEqual(confirmation.discarded, ['test.md', 'test.md'], 'Only Enter/Space approve; cancel, Escape and key-repeat do not');
    const confirmationScreenshot = path.join(os.tmpdir(), 'luggit-confirmation.png');
    await capture(confirmationScreenshot);
    await win.webContents.executeJavaScript('document.querySelector(".luggit-confirm-actions button").click(); previewConfirmation');
    console.log('Confirmation UI passed: right aligned named buttons, Enter/Space approval, cancel. Screenshot: ' + confirmationScreenshot);
    const diff = await win.webContents.executeJavaScript('runDiffTest()', true);
    assert.equal(diff.rows, 5);
    assert.deepEqual(diff.headings, ['이전', '현재', '', '변경 내용']);
    assert.equal(diff.text.includes('/dev/null'), false);
    assert.equal(diff.text.includes('diff --git'), false);
    assert.equal(diff.userSelect, 'text', 'Diff text overrides non-selectable host UI');
    win.webContents.debugger.attach('1.3');
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mousePressed', ...diff.start, button: 'left', buttons: 1, clickCount: 1 });
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseMoved', ...diff.end, button: 'left', buttons: 1 });
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseReleased', ...diff.end, button: 'left', buttons: 0, clickCount: 1 });
    assert.equal(await win.webContents.executeJavaScript('getSelection().toString()'), diff.expectedSelection, 'Mouse drag selects diff content');
    await win.webContents.executeJavaScript('document.execCommand("copy")', true);
    assert.deepEqual(await win.webContents.executeJavaScript('diffCopyEvents'), [diff.expectedSelection], 'Native copy receives the selected diff text');
    win.webContents.debugger.detach();
    const diffScreenshot = path.join(os.tmpdir(), 'luggit-diff.png');
    await capture(diffScreenshot);
    await win.webContents.executeJavaScript('lastModal.close(); void 0');
    console.log('Diff UI passed: readable new-file content, line numbers, no raw metadata. Screenshot: ' + diffScreenshot);
    await new Promise(resolve => { win.once('closed', resolve); win.close(); });
    console.log('Exit UI passed: uncommitted changes never block closing the window.');
    clearTimeout(deadline); app.exit(0);
  } catch (error) { console.error(error); clearTimeout(deadline); if (!win.isDestroyed()) win.destroy(); app.exit(1); }
});
